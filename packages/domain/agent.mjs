// Агент базовой игры для партии вдвоём (B16, B17).
//
// B16: агент — третий участник после двух людей; бросок d6 выбирает позицию лота,
//      агент ставит минимальный легальный диск, поиск идёт вправо с замыканием.
// B17: агент не строит экономику — выигранные им предприятия выбывают из игры,
//      а люди всё равно получают свои компенсации.
//
// ВЫБРАННЫЕ ТОЛКОВАНИЯ (в правилах не уточнены, издателю не приписываются;
// см. docs/01-research.md, пункт5 незавершённых вопросов):
//
//  1. (СНЯТО 28.09.2026 по официальным правилам, стр.6.) Ранее предполагалось, что агент
//     ходит со своего места в общем круге. Правила говорят прямо: ставка делается «после
//     того, как второй игрок положил диск», и «в каждом круге аукциона агент кладёт диск
//     третьим». Реализовано именно так: люди идут от первого игрока, агент всегда последний.
//     Метка первого игрока обходит только людей — агент раунд не ведёт и лоты не разбирает.
//  2. Бросок d6 рассчитан на шесть лотов партии вдвоём. Если лотов больше (переменный
//     капитал добавляет седьмой), позиция берётся по остатку от деления, чтобы бросок
//     оставался честным d6, а не превращался в d7.
//  3. Агент не получает промышленника и не участвует в подсчёте очков.
//  4. Ничья с агентом на максимуме возможна только против Моники. Применяется то же
//     правило F02: предприятие достаётся сопернику, то есть агенту, Моника берёт компенсацию.

export const AGENT_ABILITY = null;

export const isAgent = player => Boolean(player) && player.agent === true;

/** Бросок d6 на воспроизводимом генераторе состояния. Возвращает [1..6] и новое зерно. */
export function rollD6(seed) {
  const state = (Math.imul(1664525, seed >>> 0) + 1013904223) >>> 0;
  return { value: 1 + Math.floor((state / 4294967296) * 6), seed: state };
}

/**
 * Решение агента: с какого лота начать и какой диск положить.
 * legal(disc, lot) — проверка легальности из движка, чтобы правило жило в одном месте.
 * Возвращает { discId, lotId, roll, lotIndex } или null, если ставить некуда.
 */
export function chooseBid(agent, lots, legal, roll) {
  if (!lots.length) return null;
  const start = (roll - 1) % lots.length;
  const discs = agent.discs.filter(d => !d.used && !d.bonus).sort((a, b) => a.value - b.value);
  for (let step = 0; step < lots.length; step++) {
    const lotIndex = (start + step) % lots.length;
    const lot = lots[lotIndex];
    // «Минимальный легальный диск»: диски уже отсортированы по возрастанию.
    const disc = discs.find(d => legal(d, lot));
    if (disc) return { discId: disc.id, lotId: lot.id, roll, lotIndex };
  }
  return null;
}
